"""Rebuild env.Snapshot objects from a recorded episode - no sim, no ROS.

Every stack_bc zarr (demos from collect, rollouts from evaluate --record) logs the full MuJoCo
qpos per tick; QposDecoder inverts recorder.EpisodeBuffer.record on it, with the same qpos
addresses, FK (kinematics.ArmKinematics) and width measurement (gripper.WidthGauge) the live
StackEnv uses. spaces.state_vector of a rebuilt snapshot reproduces data/state.

The model and URDF come from the offline scene build (stack_bc.scene, also used by replay.py),
generated by the same steps as the live launch file.
"""

import os

import mujoco
import numpy as np
import zarr

from stack_bc import rotations as rot
from stack_bc import task
from stack_bc.env import Snapshot, has_marker
from stack_bc.gripper import GRIPPER_JOINTS, WidthGauge
from stack_bc.kinematics import ARM_JOINTS, ArmKinematics
from stack_bc.scene import DEFAULT_OUT, build_scene


MARKER_SCENE_DIR = DEFAULT_OUT + "_marker"
MARKER_WORLD = "tabletop_marker_mujoco.xml"
# DP-paper station: the marker world's physics + the paper's camera rig (worlds/dp_station_mujoco.xml).
# Same qpos layout as the marker world; the wrist camera has fovy 42.5 there (scene.camera_fovy_for).
STATION_SCENE_DIR = DEFAULT_OUT + "_dp_station"
STATION_WORLD = "dp_station_mujoco.xml"


def offline_robot(scene_dir=DEFAULT_OUT, world="tabletop_mujoco.xml"):
    """(MjModel, URDF string) of the offline-built scene (built on first use). Marker-world
    datasets: offline_robot(MARKER_SCENE_DIR, MARKER_WORLD)."""
    scene_xml = os.path.join(scene_dir, "scene.xml")
    if not os.path.exists(scene_xml):
        build_scene(scene_dir, world)
    with open(os.path.join(scene_dir, "robot_only.urdf")) as f:
        urdf = f.read()
    return mujoco.MjModel.from_xml_path(scene_xml), urdf


def dataset_model(root):
    """(MjModel, URDF) matching a stack_bc zarr's world, from its tags: the DP-paper station world
    (attrs station="dp"; different wrist camera fovy + the extra cameras), the marker world
    (marker="on"), else the plain tabletop. Checks the qpos width against the model."""
    if root.attrs.get("station", "off") == "dp":
        model, urdf = offline_robot(STATION_SCENE_DIR, STATION_WORLD)
    elif root.attrs.get("marker", "off") == "on":
        model, urdf = offline_robot(MARKER_SCENE_DIR, MARKER_WORLD)
    else:
        model, urdf = offline_robot(DEFAULT_OUT)
    if root["data/qpos"].shape[1] != model.nq:
        raise ValueError(f"dataset qpos has {root['data/qpos'].shape[1]} values, scene nq={model.nq}")
    return model, urdf


class QposDecoder:
    def __init__(self, model, kin):
        self.kin = kin
        self.gauge = WidthGauge(model)
        self.arm_adr = [model.jnt_qposadr[model.joint(n).id] for n in ARM_JOINTS]
        self.grip_adr = [model.jnt_qposadr[model.joint(n).id] for n in GRIPPER_JOINTS]
        self.cube_adr = [model.jnt_qposadr[model.body(n).jntadr[0]] for n in task.CUBE_NAMES]
        self.marker_adr = model.jnt_qposadr[model.body(task.MARKER_NAME).jntadr[0]] if has_marker(model) else None

    def __call__(self, qpos, stamp=0.0):
        q_arm, q_grip = np.asarray(qpos[self.arm_adr]), np.asarray(qpos[self.grip_adr])
        pos, R = [], []
        for adr in self.cube_adr:
            w, x, y, z = qpos[adr + 3:adr + 7]       # MuJoCo free joint: pos + quat wxyz
            pos.append(qpos[adr:adr + 3])
            R.append(rot.quat_to_matrix([x, y, z, w]))
        marker = np.array(qpos[self.marker_adr:self.marker_adr + 3]) if self.marker_adr is not None else None
        return Snapshot(stamp=float(stamp), q_arm=q_arm, q_gripper=q_grip, ee=self.kin.fk_world(q_arm),
                        width=self.gauge(q_grip), cube_pos=np.array(pos), cube_rot=np.array(R), marker_pos=marker)


def episode_slices(root):
    """[slice(start, end)] per episode of an opened zarr root."""
    ends = root["meta/episode_ends"][:]
    starts = np.concatenate([[0], ends[:-1]])
    return [slice(int(s), int(e)) for s, e in zip(starts, ends)]


def load_snapshots(path, episode, decoder):
    """All snapshots of one recorded episode."""
    root = zarr.open(os.path.expanduser(path), "r")
    sl = episode_slices(root)[episode]
    qpos, stamps = root["data/qpos"][sl], root["data/timestamp"][sl]
    return [decoder(q, t) for q, t in zip(qpos, stamps)]


def make_decoder(scene_dir=DEFAULT_OUT, world="tabletop_mujoco.xml"):
    model, urdf = offline_robot(scene_dir, world)
    return QposDecoder(model, ArmKinematics(urdf)), urdf
